export const wavyCircle = t => {
  const radius = 80 * (1 + 0.15 * Math.sin(24 * t * Math.PI));
  const angle = (2 * t + 0.5) * Math.PI;
  return [radius * Math.cos(angle), radius * Math.sin(angle)];
};

export const wavyHeptagonSweepPieces = segments.map(row => {
  if (row[0] === 'arc') {
    const [, end, radius, offset] = row;
    return {
      end,
      from: t => {
        const angle = (2 * ((t - offset) / SCALE) + 0.5) * Math.PI;
        return [radius * Math.cos(angle), radius * Math.sin(angle)];
      },
      to: wavyCircle,
    };
  }
  const [, end, t0, width, x0, x1, y0, y1] = row;
  return {
    end,
    from: t => {
      const u = (t - t0) / width;
      return [x0 + u * (x1 - x0), y0 + u * (y1 - y0)];
    },
    to: wavyCircle,
  };
});

